/* ========================================================== PART 2 — GRID */
window.Projects = (function () {
  'use strict';

  var filter = 'all';
  var grid, featured, filters, empty;

  function t(key) { return window.I18N.t(key); }
  function pick(v) { return window.I18N.pick(v); }

  /** Trimmed display value, or '' when the field was left blank. */
  function value(v) {
    var out = pick(v);
    return (out === null || out === undefined) ? '' : String(out).trim();
  }

  function matches(project) {
    var cats = project.categories || [];
    return filter === 'all' || cats.indexOf(filter) !== -1;
  }

  /** Project name, falling back to the slot id so a card is never nameless. */
  function projectName(project) {
    return value(project.name) || project.id;
  }

  /** Location · scope · year — only the parts that were filled in. */
  function projectMeta(project) {
    return [value(project.location), value(project.scope), value(project.year)]
      .filter(Boolean)
      .join('  ·  ');
  }

  function card(project, isFeatured) {
    var a = document.createElement('a');
    a.className = 'project' + (isFeatured ? ' project--featured' : '');
    /* Revealed by the shared IntersectionObserver in js/animations.js. */
    a.setAttribute('data-reveal', 'image');
    a.href = window.assetPath('pages/project.html') + '?project=' + encodeURIComponent(project.id);
    a.setAttribute('data-cursor', 'view');
    a.setAttribute('data-cursor-label', t('projects.view'));
    a.setAttribute('aria-label', projectName(project) + ' — ' + t('projects.view'));

    var media = document.createElement('div');
    media.className = 'project__media';
    var img = document.createElement('img');
    img.src = window.assetPath(project.cover || window.PROJECT_PLACEHOLDER);
    img.alt = projectName(project);
    img.loading = 'lazy';
    img.decoding = 'async';
    /* No cover uploaded yet → fall back to the neutral holding image. */
    img.addEventListener('error', function handle() {
      img.removeEventListener('error', handle);
      a.classList.add('project--placeholder');
      img.src = window.assetPath(window.PROJECT_PLACEHOLDER);
    });
    media.appendChild(img);

    var shade = document.createElement('div');
    shade.className = 'project__shade';

    var caption = document.createElement('div');
    caption.className = 'project__caption';
    caption.innerHTML =
      '<div class="project__text">' +
        '<h3 class="project__name"></h3>' +
        '<p class="project__meta"></p>' +
      '</div>' +
      '<span class="project__badge"></span>';

    caption.querySelector('.project__name').textContent = projectName(project);

    var meta = projectMeta(project);
    var metaNode = caption.querySelector('.project__meta');
    if (meta) metaNode.textContent = meta;
    else metaNode.remove();

    caption.querySelector('.project__badge').textContent = t('projects.view');

    a.appendChild(media);
    a.appendChild(shade);
    a.appendChild(caption);
    return a;
  }

  function renderFilters() {
    if (!filters) return;
    filters.innerHTML = '';

    /* Only offer a category that at least one project actually uses. */
    var used = {};
    window.SITE_DATA.projects.forEach(function (p) {
      (p.categories || []).forEach(function (c) { used[c] = true; });
    });

    var options = [{ id: 'all', label: t('projects.all') }].concat(
      window.SITE_DATA.solutions
        .filter(function (s) { return used[s.id]; })
        .map(function (s) { return { id: s.id, label: pick(s.name) }; })
    );

    if (options.length < 2) { filters.hidden = true; return; }
    filters.hidden = false;

    options.forEach(function (opt) {
      var btn = document.createElement('button');
      btn.type = 'button';
      btn.className = 'filter' + (opt.id === filter ? ' is-active' : '');
      btn.textContent = opt.label;
      btn.setAttribute('data-filter', opt.id);
      btn.setAttribute('aria-pressed', opt.id === filter ? 'true' : 'false');
      btn.addEventListener('click', function () {
        if (filter === opt.id) return;
        filter = opt.id;
        renderFilters();
        renderGrid(true);
      });
      filters.appendChild(btn);
    });
  }

  function renderGrid(animate) {
    if (!grid) return;
    var list = window.SITE_DATA.projects.filter(matches);

    featured.innerHTML = '';
    grid.innerHTML = '';

    if (!list.length) {
      empty.classList.add('is-visible');
      return;
    }
    empty.classList.remove('is-visible');

    featured.appendChild(card(list[0], true));
    list.slice(1).forEach(function (p) { grid.appendChild(card(p, false)); });

    var cards = document.querySelectorAll('.projects .project');

    if (animate) {
      /* After a filter change the visitor is already looking at the grid, so
         the cards are shown immediately and only the short filter fade runs
         — waiting for a scroll observer here would leave the grid blank. */
      cards.forEach(function (el, i) {
        el.classList.add('is-in');
        if (window.Animations && window.Animations.reduced) return;
        el.classList.add('is-filtering');
        window.setTimeout(function () { el.classList.remove('is-filtering'); }, 40 + i * 60);
      });
    } else if (window.Animations) {
      window.Animations.refresh();
    }
  }

  function init() {
    grid = document.getElementById('projectsGrid');
    featured = document.getElementById('projectsFeatured');
    filters = document.getElementById('projectFilters');
    empty = document.getElementById('projectsEmpty');
    if (!grid) return;

    renderFilters();
    renderGrid(false);

    window.addEventListener('languagechange', function () {
      renderFilters();
      renderGrid(false);
      window.Animations.refresh();
    });
  }

  return { init: init, name: projectName, meta: projectMeta, value: value };
})();


/* ===================================================== PART 3 — LIGHTBOX */
window.Lightbox = (function () {
  'use strict';

  var root, img, counter, images = [], index = 0, lastFocus = null;
  var touchX = null, touchY = null;

  function show(i) {
    if (!images.length) return;
    index = (i + images.length) % images.length;
    img.style.opacity = 0;
    var next = images[index];
    var preload = new Image();
    preload.onload = function () {
      img.src = next.src;
      img.alt = next.alt || '';
      img.style.opacity = '';
    };
    preload.src = next.src;
    counter.textContent = (index + 1) + ' / ' + images.length;
  }

  function open(list, startIndex) {
    if (!root || !list || !list.length) return;
    images = list;
    lastFocus = document.activeElement;
    root.hidden = false;
    window.requestAnimationFrame(function () { root.classList.add('is-open'); });
    document.body.classList.add('is-locked');
    document.documentElement.classList.add('has-overlay');
    show(startIndex || 0);
    root.querySelector('[data-lightbox-close]').focus();
  }

  function close() {
    if (!root || root.hidden) return;
    root.classList.remove('is-open');
    document.body.classList.remove('is-locked');
    document.documentElement.classList.remove('has-overlay');
    window.setTimeout(function () { root.hidden = true; }, 400);
    if (lastFocus && lastFocus.focus) lastFocus.focus();
  }

  /** Wire every [data-gallery-item] inside a container. */
  function attach(container) {
    var nodes = Array.prototype.slice.call(container.querySelectorAll('[data-gallery-item]'));
    nodes.forEach(function (node, i) {
      node.addEventListener('click', function (e) {
        e.preventDefault();
        /* Rebuilt on every click so items removed as broken are excluded. */
        var live = Array.prototype.slice.call(container.querySelectorAll('[data-gallery-item]'));
        var list = live.map(function (n) {
          var image = n.querySelector('img');
          return { src: image.getAttribute('data-full') || image.src, alt: image.alt };
        });
        open(list, live.indexOf(node));
      });
    });
  }

  function init() {
    root = document.getElementById('lightbox');
    if (!root) return;
    img = document.getElementById('lightboxImg');
    counter = document.getElementById('lightboxCount');

    root.querySelector('[data-lightbox-close]').addEventListener('click', close);
    root.querySelector('[data-lightbox-next]').addEventListener('click', function () { show(index + 1); });
    root.querySelector('[data-lightbox-prev]').addEventListener('click', function () { show(index - 1); });
    root.addEventListener('click', function (e) {
      if (e.target === root) close();
    });

    document.addEventListener('keydown', function (e) {
      if (root.hidden) return;
      if (e.key === 'Escape') { e.preventDefault(); close(); }
      if (e.key === 'ArrowRight') show(window.I18N.isRTL() ? index - 1 : index + 1);
      if (e.key === 'ArrowLeft') show(window.I18N.isRTL() ? index + 1 : index - 1);
    });

    /* touch swipe */
    root.addEventListener('touchstart', function (e) {
      if (!e.touches.length) return;
      touchX = e.touches[0].clientX;
      touchY = e.touches[0].clientY;
    }, { passive: true });

    root.addEventListener('touchend', function (e) {
      if (touchX === null || !e.changedTouches.length) return;
      var dx = e.changedTouches[0].clientX - touchX;
      var dy = e.changedTouches[0].clientY - touchY;
      touchX = null;
      if (Math.abs(dx) < 46 || Math.abs(dx) < Math.abs(dy)) return;
      var forward = window.I18N.isRTL() ? dx > 0 : dx < 0;
      show(forward ? index + 1 : index - 1);
    }, { passive: true });
  }

  return { init: init, open: open, close: close, attach: attach };
})();
